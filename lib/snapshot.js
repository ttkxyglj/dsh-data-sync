/**
 * DSH Data Sync — snapshot format, path remapping, applying and backups.
 *
 * The repository holds one flat snapshot: `manifest.json` describes it,
 * `files/<source>/<rel>` carries the payload verbatim, `bootstrap/` carries this
 * plugin itself so a new machine can install it from the clone, and git history
 * is the version history.
 */
import path from 'node:path'
import { promises as fsp } from 'node:fs'
import { fileURLToPath } from 'node:url'
import {
  MAX_TOTAL_BYTES,
  SCHEMA,
  ensureDir,
  isTextName,
  messageOf,
  pathInside,
  posix,
  readJson,
  sha256,
  shortId,
  stamp,
  writeJsonAtomic,
} from './util.js'
import { collectFiles } from './collect.js'

const PACKAGE_ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const BOOTSTRAP_FILES = ['package.json', 'cordis.patch.yml', 'index.js', 'client.js', 'locale', 'lib', 'icon.svg', 'README.md', 'LICENSE']
const REPO_DIRS = new Set(['files', 'bootstrap'])

/** Every file the repository should carry as its own copy of this plugin. */
async function listBootstrapFiles() {
  const rows = []
  async function walk(current) {
    let entries = []
    try {
      entries = await fsp.readdir(current, { withFileTypes: true })
    } catch {
      return
    }
    for (const entry of entries) {
      if (entry.name === 'node_modules' || entry.name === '.git') continue
      const abs = path.join(current, entry.name)
      if (entry.isDirectory()) await walk(abs)
      else if (entry.isFile()) rows.push(abs)
    }
  }
  for (const name of BOOTSTRAP_FILES) {
    const abs = path.join(PACKAGE_ROOT, name)
    try {
      const stat = await fsp.stat(abs)
      if (stat.isDirectory()) await walk(abs)
      else if (stat.isFile()) rows.push(abs)
    } catch {
      // a missing optional asset is not fatal
    }
  }
  return rows
}

/**
 * Fingerprint of the plugin copy stored in the repository, so upgrading the
 * plugin refreshes `bootstrap/` even when the payload itself did not change.
 */
export async function bootstrapDigest() {
  const rows = []
  for (const abs of await listBootstrapFiles()) {
    try {
      const rel = posix(path.relative(PACKAGE_ROOT, abs))
      rows.push(`${rel}:${sha256(await fsp.readFile(abs))}`)
    } catch {
      // unreadable file: leave it out of the fingerprint
    }
  }
  rows.sort()
  return sha256(Buffer.from(rows.join('\n'), 'utf8'))
}

function fail(code, message) {
  const error = new Error(message)
  error.code = code
  return error
}

export function newSnapshotId() {
  return `${stamp()}-${shortId()}`
}

function escapeRegExp(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/* ------------------------------------------------------------- manifest */

/** Stable fingerprint of the payload, so an unchanged push can be a no-op. */
export function payloadDigest(collected) {
  const rows = collected.files
    .map((file) => `${file.source}:${file.rel}:${file.sha256}`)
    .sort()
    .join('\n')
  return sha256(Buffer.from(rows, 'utf8'))
}

export function buildManifest(cfg, collected, snapshotId, extra = {}) {
  return {
    schema: SCHEMA,
    snapshotId,
    digest: payloadDigest(collected),
    bootstrapDigest: typeof extra.bootstrapDigest === 'string' ? extra.bootstrapDigest : '',
    createdAt: Date.now(),
    createdIso: new Date().toISOString(),
    device: { name: cfg.deviceName, platform: process.platform, releases: process.versions.node },
    profile: cfg.profile,
    sources: { ...cfg.sources },
    paths: {
      dshHome: cfg.dshHome,
      profileDir: cfg.profileDir,
      memoryDir: cfg.memoryDir,
      workspaces: cfg.workspaceRoots.map((row) => ({ label: row.label, path: row.path })),
      // The rules themselves travel: a rewrite defined on the old machine keeps
      // working on the new one without retyping it there.
      pathMappings: (cfg.pathMappings || []).map((row) => ({ from: row.from, to: row.to })),
    },
    files: collected.files.map((file) => ({
      path: `files/${file.source}/${file.rel}`,
      source: file.source,
      rel: file.rel,
      sha256: file.sha256,
      size: file.size,
    })),
    stats: { count: collected.count, bytes: collected.bytes },
    note: 'Generated by DSH Data Sync — do not edit by hand.',
  }
}

/* ------------------------------------------------------- writing a snapshot */

export async function writeSnapshotTree(cfg, manifest, collected) {
  const repoDir = cfg.repoDir
  if (!pathInside(cfg.dataDir, repoDir) || repoDir === cfg.dataDir) {
    throw fail('UNSAFE_PATH', `refusing to write a snapshot outside ${cfg.dataDir}`)
  }
  const warnings = []
  for (const dir of REPO_DIRS) {
    await fsp.rm(path.join(repoDir, dir), { recursive: true, force: true })
  }
  for (const file of collected.files) {
    const target = path.join(repoDir, 'files', file.source, ...file.rel.split('/'))
    await ensureDir(path.dirname(target))
    await fsp.writeFile(target, await fsp.readFile(file.abs))
  }
  await writeJsonAtomic(path.join(repoDir, 'manifest.json'), manifest)
  await writeJsonAtomic(path.join(repoDir, 'device.json'), {
    deviceName: cfg.deviceName,
    platform: process.platform,
    lastPushAt: manifest.createdAt,
    snapshotId: manifest.snapshotId,
    profile: cfg.profile,
  })
  await fsp.writeFile(path.join(repoDir, 'README.md'), repoReadme(manifest), 'utf8')
  await fsp.writeFile(path.join(repoDir, 'BOOTSTRAP.md'), bootstrapDoc(cfg, manifest), 'utf8')
  const bootstrapTarget = path.join(repoDir, 'bootstrap', 'dsh-data-sync')
  await ensureDir(bootstrapTarget)
  for (const source of await listBootstrapFiles()) {
    const rel = path.relative(PACKAGE_ROOT, source)
    if (rel.startsWith('..') || path.isAbsolute(rel)) continue
    const target = path.join(bootstrapTarget, rel)
    await ensureDir(path.dirname(target))
    try {
      await fsp.copyFile(source, target)
    } catch (error) {
      warnings.push(`bootstrap: could not copy ${rel}: ${messageOf(error)}`)
    }
  }
  return warnings
}

