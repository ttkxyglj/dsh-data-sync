/* -------------------------------------------------------------- mappings */

/**
 * Build the path mapping table: the paths recorded by the pushing machine, then
 * the user's explicit `pathMappings` (which win). Longest `from` first so a
 * specific rule beats a broader prefix.
 */
export function buildMappings(cfg, manifest) {
  const rows = []
  const add = (from, to, auto) => {
    if (typeof from !== 'string' || typeof to !== 'string') return
    if (from === '' || to === '' || from === to) return
    rows.push({ from, to, auto })
  }
  const saved = manifest && manifest.paths ? manifest.paths : {}
  add(saved.dshHome, cfg.dshHome, true)
  add(saved.profileDir, cfg.profileDir, true)
  add(saved.memoryDir, cfg.memoryDir, true)
  for (const workspace of Array.isArray(saved.workspaces) ? saved.workspaces : []) {
    const current = cfg.workspaceRoots.find((row) => row.label === workspace.label || row.path === workspace.path)
    if (current) add(workspace.path, current.path, true)
  }
  const byFrom = new Map()
  for (const row of rows) byFrom.set(row.from, row)
  // Rules recorded by the pushing machine first, then this machine's own rules,
  // which always win when the same prefix is listed twice.
  for (const row of Array.isArray(saved.pathMappings) ? saved.pathMappings : []) {
    if (!row || typeof row.from !== 'string' || typeof row.to !== 'string') continue
    const entry = { from: row.from, to: row.to, auto: false }
    byFrom.set(entry.from, entry)
  }
  for (const row of cfg.pathMappings || []) {
    if (!row || typeof row.from !== 'string' || typeof row.to !== 'string') continue
    byFrom.set(row.from, { from: row.from, to: row.to, auto: false })
  }
  return [...byFrom.values()].sort((left, right) => right.from.length - left.from.length)
}

/** Which workspace root of this machine a manifest workspace label maps to. */
export function buildWorkspaceMap(cfg, manifest) {
  const map = new Map()
  const saved = manifest && manifest.paths && Array.isArray(manifest.paths.workspaces) ? manifest.paths.workspaces : []
  for (const workspace of saved) {
    const current = cfg.workspaceRoots.find((row) => row.label === workspace.label || row.path === workspace.path)
    if (current) map.set(workspace.label, current.path)
  }
  return map
}

/** Replace recorded absolute paths in text payloads, keeping the separator style. */
export function remapText(text, mappings) {
  const source = String(text)
  const pairs = new Map()
  for (const mapping of mappings) {
    if (!mapping || typeof mapping.from !== 'string' || mapping.from.length < 4) continue
    const raw = mapping.from
    const to = typeof mapping.to === 'string' ? mapping.to : ''
    if (to === '' || raw === to) continue
    // One entry per spelling: plain, forward slashes, JSON-escaped backslashes.
    pairs.set(raw, to)
    pairs.set(raw.split('\\').join('/'), to.split('\\').join('/'))
    pairs.set(raw.split('/').join('\\'), to.split('/').join('\\'))
    pairs.set(raw.split('\\').join('\\\\'), to.split('\\').join('\\\\'))
  }
  const keys = [...pairs.keys()]
    .filter((key) => key.length >= 4 && key !== pairs.get(key))
    .sort((left, right) => right.length - left.length)
  if (keys.length === 0) return { text: source, replacements: 0 }
  // One pass, longest key first: a replacement can never be re-matched by a
  // shorter rule, which a sequence of `split/join` calls could do. The trailing
  // boundary stops `D:\dsh` from rewriting `D:\dsh-workplace-data`.
  const alternatives = keys.map((key) => key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')
  const pattern = new RegExp(`(?:${alternatives})(?![\\w.-])`, 'g')
  let replacements = 0
  const output = source.replace(pattern, (match) => {
    const replacement = pairs.get(match)
    if (replacement === undefined) return match
    replacements += 1
    return replacement
  })
  return { text: output, replacements }
}

/* ------------------------------------------------------------ pull planning */

function targetFor(cfg, entry, workspaceMap) {
  if (entry.source === 'config' || entry.source === 'skills') return path.join(cfg.dshHome, ...entry.rel.split('/'))
  if (entry.source === 'memory') return path.join(cfg.memoryDir, ...entry.rel.split('/'))
  if (entry.source === 'workspace') {
    const [label, ...rest] = entry.rel.split('/')
    const root = workspaceMap.get(label)
    if (!root) return null
    return path.join(root, ...rest)
  }
  return null
}

async function hashFile(file) {
  try {
    return sha256(await fsp.readFile(file))
  } catch {
    return ''
  }
}

/**
 * Manifest payload paths must stay inside the repository. `..` or an absolute
 * path in a hand-edited manifest would otherwise read an arbitrary local file.
 */
function safeManifestPath(value) {
  const text = String(value || '')
  if (!text.startsWith('files/')) return false
  if (text.includes('..')) return false
  if (text.startsWith('/') || /^[A-Za-z]:/.test(text)) return false
  return true
}

/**
 * A manifest entry must be self-consistent: the payload path has to be exactly
 * `files/<source>/<rel>`. Validating only `path` while writing to `rel` would let
 * a hand-edited manifest copy one file's bytes over an unrelated target.
 */
function entryPathMatches(entry) {
  if (!entry || typeof entry.rel !== 'string' || entry.rel === '') return false
  if (entry.rel.includes('..') || entry.rel.startsWith('/') || /^[A-Za-z]:/.test(entry.rel)) return false
  if (typeof entry.source !== 'string' || entry.source === '') return false
  return entry.path === `files/${entry.source}/${entry.rel}`
}

/** Read the payload of a manifest entry from the repository working tree. */
export async function readEntryContent(cfg, entry, mappings) {
  if (!entryPathMatches(entry)) {
    if (!safeManifestPath(entry && entry.path)) throw fail('MANIFEST_PATH', `refusing to read "${entry && entry.path}" from the repository`)
    throw fail('MANIFEST_ENTRY', `entry "${entry.rel}" does not match its payload path "${entry.path}"`)
  }
  const source = path.join(cfg.repoDir, ...entry.path.split('/'))
  const buffer = await fsp.readFile(source)
  if (typeof entry.sha256 === 'string' && entry.sha256 !== '' && sha256(buffer) !== entry.sha256) {
    throw fail('PAYLOAD_MISMATCH', `the payload for "${entry.rel}" does not match the checksum recorded in the manifest`)
  }
  if (!isTextName(entry.path) || buffer.length > 512 * 1024) return buffer
  const text = buffer.toString('utf8')
  const remapped = remapText(text, mappings)
  return remapped.replacements > 0 ? Buffer.from(remapped.text, 'utf8') : buffer
}

export async function planPull(cfg, manifest, mappings) {
  const workspaceMap = buildWorkspaceMap(cfg, manifest)
  const actions = []
  const skipped = []
  for (const entry of manifest.files || []) {
    if (!entryPathMatches(entry)) {
      skipped.push({ path: entry.rel || '?', reason: 'invalid entry in the manifest' })
      continue
    }
    // A snapshot pushed from another profile names that profile explicitly; its
    // files are not part of this profile's backup, so writing them could not be
    // rolled back.
    if (entry.source === 'config' && entry.rel.startsWith('profiles/')) {
      const owner = entry.rel.split('/')[1]
      if (owner && owner !== cfg.profile) {
        skipped.push({ path: entry.rel, reason: `belongs to profile "${owner}", this machine runs "${cfg.profile}"` })
        continue
      }
    }
    const target = targetFor(cfg, entry, workspaceMap)
    if (!target) {
      skipped.push({ path: entry.rel, reason: `workspace "${entry.rel.split('/')[0]}" is not configured on this machine` })
      continue
    }
    const allowed =
      pathInside(cfg.dshHome, target) || pathInside(cfg.memoryDir, target) || cfg.workspaceRoots.some((row) => pathInside(row.path, target))
    if (!allowed) {
      skipped.push({ path: entry.rel, reason: 'target is outside the configured roots' })
      continue
    }
    let content = null
    try {
      content = await readEntryContent(cfg, entry, mappings)
    } catch (error) {
      skipped.push({ path: entry.rel, reason: `remote payload unreadable: ${messageOf(error)}` })
      continue
    }
    const remoteHash = sha256(content)
    const localHash = await hashFile(target)
    const action = localHash === '' ? 'add' : localHash === remoteHash ? 'same' : 'update'
    actions.push({ path: entry.rel, action, source: entry.source, size: content.length, target })
  }
  return { actions, skipped, workspaceMap }
}

/* ----------------------------------------------------------------- applying */

export async function applyPull(cfg, manifest, mappings, planOverride) {
  const plan = planOverride && Array.isArray(planOverride.actions) ? planOverride : await planPull(cfg, manifest, mappings)
  const added = []
  const updated = []
  for (const action of plan.actions) {
    if (action.action === 'same') continue
    const entry = (manifest.files || []).find((row) => row.rel === action.path && row.source === action.source)
    if (!entry) continue
    const target = targetFor(cfg, entry, plan.workspaceMap)
    if (!target) continue
    const content = await readEntryContent(cfg, entry, mappings)
    try {
      await ensureDir(path.dirname(target))
      await fsp.writeFile(target, content)
    } catch (error) {
      throw fail('APPLY_FAILED', `writing ${target} failed: ${messageOf(error)}`)
    }
    if (action.action === 'add') added.push(target)
    else updated.push(target)
  }
  return { added, updated, skipped: plan.skipped, workspaceMap: plan.workspaceMap }
}

/* ------------------------------------------------------------------ backups */

export async function listBackups(cfg) {
  let entries = []
  try {
    entries = await fsp.readdir(cfg.backupDir, { withFileTypes: true })
  } catch {
    return []
  }
  const rows = []
  for (const entry of entries) {
    if (!entry.isDirectory()) continue
    const manifest = await readJson(path.join(cfg.backupDir, entry.name, 'backup.json'), null)
    if (!manifest) continue
    rows.push({
      id: entry.name,
      at: manifest.at || 0,
      reason: manifest.reason || '',
      count: Array.isArray(manifest.files) ? manifest.files.length : 0,
      bytes: Number.isFinite(manifest.bytes) ? manifest.bytes : 0,
    })
  }
  return rows.sort((left, right) => right.at - left.at)
}

/**
 * Copy the current logical payload aside. `willCreate` names the absolute paths
 * a following pull is about to create, so a rollback can remove them again.
 */
export async function backupNow(cfg, options = {}) {
  const reason = typeof options.reason === 'string' && options.reason !== '' ? options.reason : 'manual'
  const collected = await collectFiles({ ...cfg, sources: { config: true, memory: true, skills: true } })
  const id = `${stamp()}-${shortId()}`
  const dir = path.join(cfg.backupDir, id)
  const rows = []
  let bytes = 0
  for (const file of collected.files) {
    const row = { source: file.source, rel: file.rel, abs: file.abs, sha256: file.sha256, size: file.size }
    rows.push(row)
    bytes += file.size
    const target = path.join(dir, 'files', file.source, ...file.rel.split('/'))
    await ensureDir(path.dirname(target))
    await fsp.copyFile(file.abs, target)
  }
  const willCreate = Array.isArray(options.willCreate) ? options.willCreate.filter((row) => typeof row === 'string') : []
  await writeJsonAtomic(path.join(dir, 'backup.json'), {
    id,
    at: Date.now(),
    reason,
    bytes,
    files: rows,
    willCreate,
    paths: { dshHome: cfg.dshHome, profileDir: cfg.profileDir, memoryDir: cfg.memoryDir, workspaces: cfg.workspaceRoots },
  })
  await pruneBackups(cfg, Array.isArray(options.protect) ? options.protect : [])
  return { id, dir, count: rows.length, bytes }
}

/**
 * Back up exactly the files a pull is about to overwrite or create. A backup
 * built from the current-profile whitelist would miss a target outside it, and
 * the rollback of that pull would then be incomplete.
 */
export async function backupTargets(cfg, options = {}) {
  const reason = typeof options.reason === 'string' && options.reason !== '' ? options.reason : 'pre-pull'
  const targets = Array.isArray(options.targets) ? options.targets : []
  const id = `${stamp()}-${shortId()}`
  const dir = path.join(cfg.backupDir, id)
  const rows = []
  let bytes = 0
  for (const row of targets) {
    const abs = path.resolve(String((row && (row.target || row.abs)) || ''))
    if (abs === '' || abs === path.resolve('.')) continue
    let stat = null
    try {
      stat = await fsp.stat(abs)
    } catch {
      continue
    }
    if (!stat.isFile()) continue
    let content = null
    try {
      content = await fsp.readFile(abs)
    } catch (error) {
      throw fail('BACKUP_READ', `the pre-pull backup could not read ${abs}: ${messageOf(error)}`)
    }
    const source = typeof row.source === 'string' && row.source !== '' ? row.source : 'config'
    const rel = typeof row.rel === 'string' && row.rel !== '' ? row.rel : path.basename(abs)
    const stored = path.join(dir, 'files', source, ...rel.split('/'))
    await ensureDir(path.dirname(stored))
    await fsp.writeFile(stored, content)
    rows.push({ source, rel, abs, sha256: sha256(content), size: content.length })
    bytes += content.length
  }
  const willCreate = Array.isArray(options.willCreate) ? options.willCreate.filter((row) => typeof row === 'string') : []
  await writeJsonAtomic(path.join(dir, 'backup.json'), {
    id,
    at: Date.now(),
    reason,
    bytes,
    files: rows,
    willCreate,
    paths: { dshHome: cfg.dshHome, profileDir: cfg.profileDir, memoryDir: cfg.memoryDir, workspaces: cfg.workspaceRoots },
  })
  await pruneBackups(cfg, Array.isArray(options.protect) ? options.protect : [])
  return { id, dir, count: rows.length, bytes }
}

/**
 * Keep the newest `keepSnapshots` backups, never deleting a protected id — a
 * rollback creates a safety backup, and pruning right after must not remove the
 * very backup it is about to restore from.
 */
export async function pruneBackups(cfg, protectedIds = []) {
  const protect = new Set(protectedIds.filter((value) => typeof value === 'string' && value !== ''))
  const rows = await listBackups(cfg)
  let kept = 0
  for (const row of rows) {
    if (protect.has(row.id)) continue
    if (kept < cfg.keepSnapshots) {
      kept += 1
      continue
    }
    await fsp.rm(path.join(cfg.backupDir, row.id), { recursive: true, force: true }).catch(() => {})
  }
}

export async function rollbackTo(cfg, backupId) {
  const id = String(backupId || '').trim()
  if (!id || id === '.' || id === '..' || !/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(id)) throw fail('BACKUP_ID_INVALID', 'a backup id is required')
  const dir = path.join(cfg.backupDir, id)
  const manifest = await readJson(path.join(dir, 'backup.json'), null)
  if (!manifest) throw fail('BACKUP_NOT_FOUND', `no backup named ${id} exists`)
  const safety = await backupNow(cfg, { reason: `pre-rollback:${id}`, protect: [id] })
  let restored = 0
  const skipped = []
  for (const row of manifest.files || []) {
    const abs = String(row.abs || '')
    const allowed =
      pathInside(cfg.dshHome, abs) || pathInside(cfg.memoryDir, abs) || cfg.workspaceRoots.some((root) => pathInside(root.path, abs))
    if (!allowed) {
      skipped.push(abs)
      continue
    }
    const source = path.join(dir, 'files', row.source, ...String(row.rel || '').split('/'))
    try {
      const content = await fsp.readFile(source)
      await ensureDir(path.dirname(abs))
      await fsp.writeFile(abs, content)
      restored += 1
    } catch (error) {
      skipped.push(`${abs} (${messageOf(error)})`)
    }
  }
  for (const abs of Array.isArray(manifest.willCreate) ? manifest.willCreate : []) {
    if (!pathInside(cfg.dshHome, abs) && !pathInside(cfg.memoryDir, abs) && !cfg.workspaceRoots.some((root) => pathInside(root.path, abs))) continue
    await fsp.rm(abs, { force: true }).catch(() => {})
  }
  return { restored, skipped, safetyBackupId: safety.id }
}

